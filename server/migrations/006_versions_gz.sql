-- Сжатие документов в истории.
--
-- Документ доски — это JSON с огромным количеством повторов (ключи полей, id,
-- цвета), и gzip уменьшает его примерно в десять раз. Без сжатия «хранить всю
-- историю» упирается в диск: активная правка даёт сотни версий в день по паре
-- сотен килобайт каждая. Со сжатием тот же объём стоит десятую часть, и потолок
-- в 40 версий становится не нужен.
--
-- Старая колонка doc остаётся: строки, записанные до этой миграции, читаются
-- как раньше. Переписывать их разом значило бы держать всю историю в памяти
-- и рисковать миграцией ради экономии, которая придёт сама при следующей правке.
ALTER TABLE board_versions ADD COLUMN doc_gz BLOB;

-- Индекс по времени: прореживание старых версий ходит именно по нему.
CREATE INDEX idx_bv_at ON board_versions(board_id, at);

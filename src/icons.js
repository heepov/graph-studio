/* Единый набор значков.

   Раньше глифы («＋», «▾», «⚙», «🗑», «🔍») лежали россыпью в шаблонных строках:
   разного веса и высоты, часть — эмодзи, которые в каждой ОС рисуются по-своему
   и в тёмной теме светятся собственным цветом. Здесь форма одна.

   Сами контуры — <symbol> в index.html, тут только ссылка на них. icon() отдаёт
   СТРОКУ: её можно подставить ровно туда, где стоял глиф, ничего не меняя вокруг.

   Спрайт, а не контур в каждом вызове: renderTable строит тысячи ячеек, а
   patchList сравнивает разметку строкой — по 400 байт путей на значок раздуло бы
   и то, и другое.

   ⚠️ В контекстное меню и <option> значок строкой не положить: showCtx() и opts()
   прогоняют подписи через esc(), а showCtx ещё и ищет пункт по сырой подписи. */
export function icon(name, cls) {
  return `<svg class="i${cls ? ' ' + cls : ''}" aria-hidden="true"><use href="#i-${name}"/></svg>`;
}
